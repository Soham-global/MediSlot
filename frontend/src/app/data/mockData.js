export const mapHospital = (hospital) => ({
  id: hospital.id,
  name: hospital.name,
  location:
    `${hospital.address || ""}${hospital.city ? `, ${hospital.city}` : ""}`.replace(
      /^, /,
      "",
    ),
  desc: `Open ${(hospital.openingTime || "09:00").slice(0, 5)} – ${(hospital.closingTime || "17:00").slice(0, 5)}`,
  doctors: hospital.doctorCount || "",
  photo: "city",
  image: hospital.imageUrl || null,
});
export const mapDoctor = (doctor) => ({
  id: doctor.id,
  name: doctor.name,
  initial: doctor.name
    .split(" ")
    .filter(Boolean)
    .slice(-2)
    .map((x) => x[0])
    .join(""),
  specialty: doctor.specialization || doctor.department?.name || "Specialist",
  experience: `${doctor.experienceYears || 0}+ years experience`,
  rating: "4.6 (120)",
  hospital: doctor.hospital?.name ? `${doctor.hospital.name}${doctor.hospital.city ? ", " + doctor.hospital.city : ""}` : "Partner Hospital",
  time: "09:00 AM – 05:00 PM",
  color: "#dceeff",
  department: doctor.department?.name || "",
  departmentId: doctor.department?.id || null,
  qualification: doctor.qualification || "",
  about: doctor.about || "",
  weeklyTimings: doctor.weeklyTimings || [],
  hospitalCity: doctor.hospital?.city || "",
  experienceYears: doctor.experienceYears || 0,
  image: doctor.profileImageUrl || null,
  availableOnDate: doctor.availableOnDate,
  nextAvailableDate: doctor.nextAvailableDate || null,
});
