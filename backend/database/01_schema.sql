-- Medi-Slot: tables (PostgreSQL 13+). Safe to re-run: every statement uses IF NOT EXISTS.
-- Run against an EMPTY database, e.g.:  psql -d medislot_db -f 01_schema.sql

CREATE TABLE IF NOT EXISTS employees (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code  VARCHAR(40)  NOT NULL UNIQUE,
    name           VARCHAR(150) NOT NULL,
    email          VARCHAR(200) NOT NULL UNIQUE,
    phone          VARCHAR(30),
    plant_location VARCHAR(150),
    password_hash  VARCHAR(100) NOT NULL,          -- BCrypt hash
    active         BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS hospitals (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(200) NOT NULL,
    address      VARCHAR(300) NOT NULL,
    city         VARCHAR(100) NOT NULL,
    phone        VARCHAR(30)  NOT NULL,
    email        VARCHAR(200) NOT NULL,
    opening_time TIME         NOT NULL DEFAULT '09:00',
    closing_time TIME         NOT NULL DEFAULT '17:00',
    active       BOOLEAN      NOT NULL DEFAULT TRUE,  -- FALSE = archived
    image_url    VARCHAR(500)                         -- Cloudinary photo URL (https)
);

CREATE TABLE IF NOT EXISTS departments (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS super_admins (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(150) NOT NULL,
    email         VARCHAR(200) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS hospital_admins (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id   BIGINT       NOT NULL REFERENCES hospitals (id),
    name          VARCHAR(150) NOT NULL,
    email         VARCHAR(200) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS doctors (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id       BIGINT       NOT NULL REFERENCES hospitals (id),
    department_id     BIGINT       NOT NULL REFERENCES departments (id),
    name              VARCHAR(150) NOT NULL,
    specialization    VARCHAR(150) NOT NULL,
    qualification     VARCHAR(200),
    experience_years  INTEGER      NOT NULL DEFAULT 0,
    email             VARCHAR(200),
    phone             VARCHAR(30),
    consultation_fee  NUMERIC(10, 2),
    about             VARCHAR(2000),
    profile_image_url VARCHAR(500),
    active            BOOLEAN      NOT NULL DEFAULT TRUE
);

-- Weekly availability. day_of_week: 1 = Monday ... 7 = Sunday
CREATE TABLE IF NOT EXISTS doctor_schedules (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id             BIGINT  NOT NULL REFERENCES doctors (id),
    day_of_week           INTEGER NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    start_time            TIME    NOT NULL,
    end_time              TIME    NOT NULL,
    slot_duration_minutes INTEGER NOT NULL,
    CONSTRAINT uq_doctor_day UNIQUE (doctor_id, day_of_week)
);

-- Bookable time windows generated from doctor_schedules
CREATE TABLE IF NOT EXISTS slots (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id  BIGINT  NOT NULL REFERENCES doctors (id),
    slot_date  DATE    NOT NULL,
    start_time TIME    NOT NULL,
    end_time   TIME    NOT NULL,
    booked     BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_slot UNIQUE (doctor_id, slot_date, start_time)
);
CREATE INDEX IF NOT EXISTS idx_slot_lookup ON slots (doctor_id, slot_date, booked);

CREATE TABLE IF NOT EXISTS appointments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id  BIGINT       NOT NULL REFERENCES employees (id),
    doctor_id    BIGINT       NOT NULL REFERENCES doctors (id),
    hospital_id  BIGINT       NOT NULL REFERENCES hospitals (id),
    slot_id      BIGINT       NOT NULL REFERENCES slots (id),
    status       VARCHAR(20)  NOT NULL DEFAULT 'BOOKED'
                 CHECK (status IN ('BOOKED', 'CONFIRMED', 'CANCELLED', 'COMPLETED', 'NO_SHOW')),
    reason       VARCHAR(500),
    created_at   TIMESTAMP(6) NOT NULL DEFAULT now(),
    updated_at   TIMESTAMP(6) NOT NULL DEFAULT now(),
    cancelled_by VARCHAR(20)
);
CREATE INDEX IF NOT EXISTS idx_appt_employee ON appointments (employee_id);
CREATE INDEX IF NOT EXISTS idx_appt_hospital ON appointments (hospital_id);
CREATE INDEX IF NOT EXISTS idx_appt_slot     ON appointments (slot_id);

-- Safety net against double booking: at most ONE live appointment per slot
CREATE UNIQUE INDEX IF NOT EXISTS uq_live_appointment_per_slot
    ON appointments (slot_id) WHERE status IN ('BOOKED', 'CONFIRMED');

